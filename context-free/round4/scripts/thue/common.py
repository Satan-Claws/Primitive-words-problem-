"""thue: escape certificates for A'-type (free loops) decompositions with x_j = eps.

Generated words of a window W = alpha v1..vm beta are conjugate to sigma r, sigma in M={v1..vm}*,
r = beta alpha.  Certificates (each PROVES that all sigma r are primitive, for ALL sigma in M):
  UF : a word delta occurring exactly once in r with delta not a factor of s sigma p for any
       sigma in M (s = last |delta|-1 letters of r, p = first |delta|-1).  Exact automaton check.
  PAR: all psi(v_j) parallel to a primitive (al,be); gcd(A+n al, B+n be) = 1 for every reachable n.
"""
from math import gcd
from itertools import combinations

def primitive(w):
    return len(w) > 0 and (w + w).find(w, 1) == len(w)

def tm(n):
    return ''.join('ab'[bin(i).count('1') % 2] for i in range(n))

def kmp_table(d):
    f = [0] * (len(d) + 1); f[0] = -1; k = -1
    for i, c in enumerate(d):
        while k >= 0 and d[k] != c:
            k = f[k]
        k += 1; f[i + 1] = k
    return f

class KMP:
    def __init__(self, d):
        self.d = d; self.f = kmp_table(d); self.n = len(d)
        self.cache = {}
    def step(self, q, c):
        key = (q, c)
        if key in self.cache: return self.cache[key]
        k = q
        if k == self.n: k = self.f[k]
        while k >= 0 and self.d[k] != c:
            k = self.f[k]
        r = k + 1
        self.cache[key] = r
        return r
    def run(self, q, w):
        """returns (final state, hit) where hit = full match occurred"""
        hit = False
        for c in w:
            q = self.step(q, c)
            if q == self.n: hit = True
        return q, hit

def delta_free(delta, s, loops, p):
    """True iff delta is not a factor of s sigma p for every sigma in loops*."""
    A = KMP(delta)
    q0, h = A.run(0, s)
    if h: return False
    seen = {q0}; stack = [q0]
    while stack:
        q = stack.pop()
        _, h = A.run(q, p)
        if h: return False
        for v in loops:
            q2, h = A.run(q, v)
            if h: return False
            if q2 not in seen:
                seen.add(q2); stack.append(q2)
    return True

def count_occ(w, d):
    c = 0; i = w.find(d)
    while i >= 0:
        c += 1; i = w.find(d, i + 1)
    return c

def uf_cert(r, loops, maxlam=None):
    """search for a UF certificate; return delta or None"""
    n = len(r)
    if maxlam is None: maxlam = n // 2 + 1
    tried = set()
    for i in range(n):
        for lam in range(1, maxlam + 1):
            if i + lam > n: break
            d = r[i:i + lam]
            if count_occ(r, d) == 1:
                if d not in tried and 2 * lam - 2 <= n:
                    tried.add(d)
                    s = r[n - (lam - 1):] if lam > 1 else ''
                    p = r[:lam - 1]
                    if delta_free(d, s, loops, p):
                        return d
                break   # longer extensions from i are also unique; minimal one tried
    return None

def psi(w):
    return (w.count('a'), w.count('b'))

def par_cert(r, loops):
    vs = [psi(v) for v in loops]
    a0, b0 = vs[0]; g = gcd(a0, b0); al, be = a0 // g, b0 // g
    cs = []
    for (x, y) in vs:
        if x * be != y * al: return False
        cs.append((x + y) // (al + be))
    A, B = psi(r)
    det = abs(be * A - al * B)
    if det == 0: return False
    # reachable n: semigroup generated by cs; check n up to bound
    bound = max(cs) * max(cs) + det + 5
    reach = [False] * (bound + 1); reach[0] = True
    for n in range(1, bound + 1):
        reach[n] = any(n >= c and reach[n - c] for c in cs)
    for n in range(bound + 1):
        if reach[n] and gcd(A + n * al, B + n * be) != 1:
            return False
    return True

def windows(W, marks, m, maxlen):
    """x_j = eps windows: cut points c0<...<cm (circular start allowed? no: linear), each piece has a mark."""
    n = len(W)
    mk = [0] * (n + 1)
    for i in range(n): mk[i + 1] = mk[i] + (1 if i in marks else 0)
    for c0 in range(n):
        def rec(cuts):
            if len(cuts) == m + 1:
                yield tuple(cuts); return
            last = cuts[-1]
            for c in range(last + 1, min(n, cuts[0] + maxlen) + 1):
                if mk[c] - mk[last] > 0:
                    yield from rec(cuts + [c])
        yield from rec([c0])

def bounded_attack(r, loops, maxsig):
    """search sigma in M with |sigma| <= maxsig making sigma r non-primitive (BFS on words)."""
    frontier = {''}; seen = {''}
    while frontier:
        nf = set()
        for s in frontier:
            if not primitive(s + r): return s
            for v in loops:
                t = s + v
                if len(t) <= maxsig and t not in seen:
                    seen.add(t); nf.add(t)
        frontier = nf
    return None

def in_monoid(w, loops):
    ok = [False] * (len(w) + 1); ok[0] = True
    for i in range(1, len(w) + 1):
        ok[i] = any(len(v) <= i and ok[i - len(v)] and w[i - len(v):i] == v for v in loops)
    return ok[-1]

def factor_of_monoid(r, loops):
    """is r a factor of some word of loops* ? (KMP states over the monoid)"""
    A = KMP(r); seen = {0}; st = [0]
    while st:
        q = st.pop()
        for v in loops:
            q2, h = A.run(q, v)
            if h: return True
            if q2 not in seen: seen.add(q2); st.append(q2)
    return False

def exact_attack(r, loops, maxN):
    """Exact: returns ('case2', sigma) for some sigma in M, |t|<|r|, sigma r = t^e (e>=2) with |sigma r|<=maxN;
    'case1?' if r is a factor of M (long-t powers not excluded); None if neither (for |sigma r| <= maxN,
    and case1 excluded for all lengths)."""
    n = len(r)
    for N in range(n, maxN + 1):
        for e in range(2, N + 1):
            if N % e: continue
            P = N // e
            if P >= n: continue
            t = r[n - P:]
            w = t * e
            if w.endswith(r):
                sig = w[:N - n]
                if in_monoid(sig, loops): return ('case2', sig)
    if factor_of_monoid(r, loops): return 'case1?'
    return None

"""S3F [computational]: M=2 (coords x1,x2,y1,y2). Over pool covers (full-rank laminar pieces, gen entries<=E,
offsets c in {1..C}^4, Delta-avoiding checked on diagonal up to DB), find the largest N0 such that some
selection covers all of NE_2 in box [1..T]^4 and has ply<=1 at every box point of l1-norm < N0.
Optional rho>0: force a piece with CYCLIC quotient Z^4/ZV = Z/2^rho (chain-type, poly_T2b) into the cover;
chain-type pieces get offsets up to C+1. (The literal chain e_x1,e_x1+2e_x2,e_x2+2e_y1,e_y1+2e_y2 is never
Delta-avoiding: its y-x projections positively span R^2 and Z/8 is generated by Delta.)
Usage: python3 s3f_ilp.py T C E rho"""
import sys, itertools, numpy as np
from scipy.optimize import milp, LinearConstraint, Bounds
from scipy.sparse import csr_matrix
from s3f_pool import families
T,C,E,CH=map(int,sys.argv[1:5]); DB=30; d=4
F=families(d,E)
def cyc2(V,rho):
    if round(abs(np.linalg.det(V)))!=2**rho: return False
    if rho==0: return False
    g=0
    for R in itertools.combinations(range(4),3):
        for Cc in itertools.combinations(range(4),3):
            g=np.gcd(g,int(round(abs(np.linalg.det(V[np.ix_(R,Cc)])))))
    return g==1
pts=np.array([p for p in itertools.product(range(1,T+1),repeat=d) if (p[0],p[1])!=(p[2],p[3])])
diag=np.array([(u,v,u,v) for u in range(1,DB) for v in range(1,DB)])
def member(Vi,c,P):
    q=(P-c)@Vi.T
    r=np.round(q); return np.all(np.abs(q-r)<1e-7,axis=1)&np.all(r>-1e-9,axis=1)
pieces=[];cols=[]
for V in F:
    Vi=np.linalg.inv(V)
    isc=CH>0 and cyc2(V,CH)
    for c in itertools.product(range(1,C+2 if isc else C+1),repeat=d):
        c=np.array(c)
        if member(Vi,c,diag).any(): continue
        m=member(Vi,c,pts)
        if not m.any(): continue
        pieces.append((V,c)); cols.append(np.nonzero(m)[0])
ischain=[CH>0 and cyc2(V,CH) for V,c in pieces]
print("pool",len(pieces),"chainpieces",sum(ischain),"pts",len(pts),flush=True)
rows=np.concatenate(cols); colidx=np.concatenate([[j]*len(c) for j,c in enumerate(cols)])
A=csr_matrix((np.ones(len(rows)),(rows,colidx)),shape=(len(pts),len(pieces)))
norms=pts.sum(1)
def feasible(N0):
    low=norms<N0
    ub=np.where(low,1,np.inf)
    cons=[LinearConstraint(A,np.ones(len(pts)),ub)]
    if CH:
        a=np.array(ischain,float); cons.append(LinearConstraint(a[None,:],1,np.inf))
    res=milp(np.ones(len(pieces))*1e-3,constraints=cons,integrality=np.ones(len(pieces)),
             bounds=Bounds(0,1),options={"time_limit":300})
    return res
best=None
for N0 in range(6,4*T+2):
    res=feasible(N0)
    ok=res.status==0
    print("N0",N0,"feasible" if ok else "infeasible/status%d"%res.status,flush=True)
    if not ok: break
    best=(N0,res)
if best:
    N0,res=best; x=np.round(res.x).astype(int); sel=[pieces[j] for j in range(len(pieces)) if x[j]]
    ply=A@x
    two=[(norms[i],tuple(pts[i])) for i in range(len(pts)) if ply[i]>=2]
    print("max N0 with ply<=1 below N0:",N0," min norm of ply>=2 box point:",min(two)[0] if two else None, min(two) if two else "")
    for V,c in sel: print(" c",tuple(c),"V",[tuple(v) for v in V.T])

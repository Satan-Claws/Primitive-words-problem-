"""recon_checks.py -- two small checks for round2/reports/recon.md.

(1) Ito/E-S refinement (poly_S3D): laminar list V = {e1, 2e_i+e_{i+1} (i=1..rho), e_{rho+1}} in N^{rho+1}
    has d = 1 and primitive kernel vector with entries 2^rho. The lex-min (Stanley) refinement therefore
    has offsets of norm >= 2^{rho-1}: the bound ||c||_1 <= nK is NOT inherited by the refined pieces.
(2) Lemma F offsets (poly_G4): toy unambiguous grammar S -> aU, U -> BUA | a, B -> b, A -> aC, C -> bC | b.
    In (ab*)^n its unique skeleton has offset b^{n-2} in block 1; fixing every other free block to 1
    leaves a 1-coordinate face whose piece has offset n-2 = Theta(n), not O(r K) with r = 1.
"""
import itertools
from fractions import Fraction
import sympy as sp

def check_ito(rho):
    N = rho + 1
    cols = [[1] + [0]*rho]
    for i in range(rho):
        v = [0]*N; v[i] = 2; v[i+1] = 1; cols.append(v)
    w = [0]*N; w[rho] = 1; cols.append(w)
    A = sp.Matrix(cols).T
    ker = A.nullspace()
    assert len(ker) == 1  # d = 1
    z = ker[0]; den = sp.ilcm(*[sp.fraction(x)[1] for x in z]); z = z*den
    g = sp.igcd(*[int(x) for x in z]); z = [int(x)//g for x in z]
    return z, max(abs(x) for x in z)

for rho in range(1, 9):
    z, mx = check_ito(rho)
    assert mx == 2**rho, (rho, z)
print("(1) kernel entries max = 2^rho for rho=1..8  OK; e.g. rho=4:", check_ito(4)[0])
# lex-min refinement: non-lexmin ideal is generated by z^+ or z^- (d=1); any Stanley piece not
# containing the largest generator coordinate as a free period has offsets up to that coordinate.
z, _ = check_ito(6)
gen = [max(x, 0) for x in z] if z[0] < 0 else [max(-x, 0) for x in z]
print("    rho=6 lex-min ideal generator (coeffs on e1, v1..v6, w):", gen)

def derive_words(n):
    """all words of the toy grammar with exactly n a's (bounded b's per C-block to 2)"""
    out = []
    j = n - 2
    if j < 0: return out
    for tail in itertools.product([1, 2], repeat=j):
        word = 'a' + 'b'*j + 'a' + ''.join('a' + 'b'*t for t in tail)
        out.append(word)
    return out

for n in range(2, 9):
    for wd in derive_words(n):
        blocks = wd.split('a')[1:]
        assert len(blocks) == n and len(blocks[0]) == n - 2
print("(2) toy grammar: block-1 offset = n-2 for n=2..8 OK (face fixing blocks 3..n to 1 keeps offset n-2)")
